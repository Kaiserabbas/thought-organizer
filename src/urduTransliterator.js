/**
 * Checks if a string is primarily Roman Urdu
 */
export function isLikelyRomanUrdu(text) {
  if (!text || typeof text !== 'string') return false;
  const words = text.toLowerCase().trim().split(/\s+/);
  if (words.length === 0) return false;

  let matchCount = 0;
  for (const w of words) {
    const clean = w.replace(/[^a-z]/g, '');
    if (ROMAN_URDU_DICTIONARY[clean]) {
      matchCount++;
    }
  }

  // If at least 30% of words match common Urdu vocabulary in Latin script
  return matchCount / words.length >= 0.3 || (words.length === 1 && matchCount === 1);
}

/**
 * Translates Roman Urdu words into Urdu script offline.
 * Preserves punctuation, numbers, and genuine English words.
 */
export function transliterateRomanUrduOffline(text) {
  if (!text || typeof text !== 'string') return text;

  // Split into tokens (words and punctuation)
  const tokens = text.split(/(\s+|[.,!?;:۔،؟])/);

  const converted = tokens.map((token) => {
    // If it's whitespace or punctuation, return as is
    if (/^\s+$/.test(token) || /^[.,!?;:۔،؟]$/.test(token)) {
      if (token === '?') return '؟';
      if (token === ',') return '،';
      if (token === '.') return '۔';
      return token;
    }

    const clean = token.toLowerCase().replace(/[^a-z_]/g, '');
    if (ROMAN_URDU_DICTIONARY[clean]) {
      return ROMAN_URDU_DICTIONARY[clean];
    }

    return token;
  });

  return converted.join('');
}
